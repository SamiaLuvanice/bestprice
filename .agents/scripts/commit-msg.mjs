#!/usr/bin/env node
// Política de commits, aplicada por hook (commit-msg) e no CI (--range):
//   1. Conventional Commits no título: tipo(escopo)!: descrição
//   2. Autoria sempre humana: sem trailer Co-Authored-By de agente nem rodapé de ferramenta
//   3. (somente no hook) sem commit direto em branch protegida de harness.yaml
//
//   node .agents/scripts/commit-msg.mjs .git/COMMIT_EDITMSG
//   node .agents/scripts/commit-msg.mjs --range origin/main..HEAD
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { asList, git, loadHarness } from "./lib.mjs";

export const TYPES = ["feat", "fix", "docs", "style", "refactor", "perf", "test", "build", "ci", "chore", "revert"];
const HEADER = new RegExp(`^(${TYPES.join("|")})(\\([a-z0-9._/-]+\\))?!?: \\S.*$`);
const AUTO_GENERATED = [/^Merge (branch|pull request|remote-tracking branch) /, /^Revert ".+"/, /^(fixup|squash|amend)! /];
// Nomes inequívocos de produto: bastam no nome do coautor (palavra inteira).
// Nomes que também são de gente (Devin, Jules, Cursor, Aider…) só contam pelo e-mail.
const AGENT_PRODUCTS = "claude|anthropic|copilot|chatgpt|openai|codex|opencode|gemini|windsurf|codeium|tabnine";
const BOT_EMAILS = [
  "noreply@anthropic\\.com",
  "[^>]*\\[bot\\]@users\\.noreply\\.github\\.com",
  "copilot@github\\.com",
  "[^>]*@(?:openai|anthropic|cursor|cognition\\.ai|devin\\.ai|codeium|windsurf)\\.com",
];
const ATTRIBUTION = [
  new RegExp(`^co-authored-by:[^<\\n]*\\b(${AGENT_PRODUCTS})\\b`, "im"),
  new RegExp(`^co-authored-by:[^\\n]*<(${BOT_EMAILS.join("|")})>`, "im"),
  /generated (with|by) .*(claude|copilot|cursor|codex|opencode|chatgpt|gemini)/i,
  /🤖/u,
];
export const BYPASS_TOKEN = "[bootstrap-guard]";

/** Remove comentários do editor (#) e a área de diff do `git commit -v`. */
export function cleanMessage(raw) {
  const scissors = raw.indexOf("# ------------------------ >8 ------------------------");
  const body = scissors >= 0 ? raw.slice(0, scissors) : raw;
  return body
    .split(/\r?\n/)
    .filter((line) => !line.startsWith("#"))
    .join("\n")
    .trim();
}

export function validateMessage(raw) {
  const message = cleanMessage(raw);
  const errors = [];
  if (message === "") return ["mensagem vazia"];
  const header = message.split("\n")[0];
  const autoGenerated = AUTO_GENERATED.some((pattern) => pattern.test(header));
  if (!autoGenerated) {
    if (!HEADER.test(header)) {
      errors.push(`título fora do Conventional Commits: "${header}" (ex.: feat(about): adiciona seção)`);
    } else if (header.length > 100) {
      errors.push(`título com ${header.length} caracteres (máximo 100)`);
    }
  }
  for (const pattern of ATTRIBUTION) {
    if (pattern.test(message)) {
      errors.push("atribuição a agente de IA não é permitida (Co-Authored-By de agente, rodapé ou assinatura de ferramenta)");
      break;
    }
  }
  return errors;
}

export function protectedBranchError(branch, message, protectedBranches) {
  if (!branch || !protectedBranches.includes(branch)) return null;
  if (message.includes(BYPASS_TOKEN)) return null;
  return `commit direto na branch protegida '${branch}'. Crie uma branch de trabalho e abra um PR.`;
}

function checkRange(range) {
  const output = git(["log", "--format=%H%x1f%B%x1e", range]);
  const failures = [];
  for (const record of output.split("\x1e")) {
    if (record.trim() === "") continue;
    const [sha, message] = record.trim().split("\x1f");
    const errors = validateMessage(message ?? "");
    if (errors.length > 0) failures.push(`${sha.slice(0, 7)}: ${errors.join("; ")}`);
  }
  return failures;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const args = process.argv.slice(2);
  let failures = [];
  if (args[0] === "--range") {
    if (!args[1]) {
      console.error("Uso: commit-msg.mjs --range <base>..<head>");
      process.exit(2);
    }
    failures = checkRange(args[1]);
  } else {
    const raw = readFileSync(args[0] ?? ".git/COMMIT_EDITMSG", "utf8");
    failures = validateMessage(raw);
    const branch = git(["symbolic-ref", "--quiet", "--short", "HEAD"], { allowFailure: true });
    const protectedBranches = asList(loadHarness().git?.protected_branches);
    const guard = protectedBranchError(branch, raw, protectedBranches);
    if (guard) failures.push(guard);
  }
  if (failures.length > 0) {
    console.error("\nCommit recusado pela política do harness (.agents/rules/git.md):");
    for (const failure of failures) console.error(`  - ${failure}`);
    console.error("");
    process.exit(1);
  }
}
